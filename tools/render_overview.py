"""Generate the overview paper (the first of the three) from its hand-written text and the single sources.

  python tools/render_overview.py      → src/overview/01-overview.cited.md, 80-declarations.md, 90-references.md, ORDER.txt

Hand-written: src/overview/01-overview.md. Every number it prints about the series is checked here against
programme.yaml (facts, stats) and the release record of Series 00; the build stops on a difference.
"""
import json
import re
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE / "tools"))
import refs  # noqa: E402

SRC = HERE / "src"
OUT = SRC / "overview"
SERIES = HERE.parent
sys.stdout.reconfigure(encoding="utf-8", errors="replace")


def facts():
    """the numbers the text may print, from the single sources"""
    p = yaml.safe_load((SERIES / "programme.yaml").read_text(encoding="utf-8"))
    st = json.loads((SERIES / "release-kit" / "state.json").read_text(encoding="utf-8"))
    t, s = p["facts"]["totals"], p["stats"]["totals"]
    works = p["facts"]["works"]
    return {"volumes": str(t["volumes"]), "pages": f"{t['pages']:,}", "chapters": s["chapters"],
            "formulas": s["formulas"].rstrip("+"), "statements": s["statements"].rstrip("+"),
            "algorithms": s["algorithms"], "figures": s["figures_and_plates"],
            "first": min(w["publication_date"] for w in works), "last_work": max(w["publication_date"] for w in works),
            "overview": st["publication_date"], "edition": p["programme"]["edition"],
            "version": works[0]["version"]}


def check_numbers(text):
    f = facts()
    want = [f"{f['volumes']} volumes", f"{f['pages']} pages", f"{f['chapters']} chapters", f"more than {f['formulas']}",
            f"more than {f['statements']}", f"{f['algorithms']} numbered algorithms", f"{f['figures']} numbered figures",
            f["edition"], f"version {f['version']}"]
    flat = " ".join(text.split())
    missing = [w for w in want if w not in flat]
    d = {"2026-10-20": "20", "2026-10-26": "26"}
    if f["first"] != "2026-10-20" or f["overview"] != "2026-10-26" or "between 20 and 26 October 2026" not in flat:
        missing.append(f"release dates (first {f['first']}, overview {f['overview']}) and the text's date range")
    if missing:
        sys.exit("overview: numbers not as in the single sources: " + "; ".join(missing))
    return len(want) + 1


def main():
    text = (OUT / "01-overview.md").read_text(encoding="utf-8")
    n = check_numbers(text)
    decl = "# Declarations {.unnumbered}\n\n" + (SRC / "declarations.md").read_text(encoding="utf-8").strip() + "\n"
    decl = decl.replace("no problem in this\npaper was posed by Grothendieck unless the card says so.",
                        "the image of the rising sea is his, as reported\nin [@McLarty2007].")
    assert "posed by Grothendieck" not in decl
    # this paper selects no theses or problems and has no machine-readable file of its own
    for old, new in (("the author selected the theses and problems and reviewed every statement",
                      "the author reviewed every statement"),
                     ("The extraction scripts and the list of extracted items, the record of the literature\ncheck, the "
                      "reference check, the Lean statements, the figures with their data and sources, and the machine-readable "
                      "file\nof the paper are in the repository",
                      "The sources of this paper, its figures with their data and source code, and the scripts\nthat checked "
                      "it and the records of the checks are in the repository")):
        assert decl.count(old) == 1, old[:60]
        decl = decl.replace(old, new)
    # Series 00 is "the overview volume" in this paper, whose own title is "An Overview"
    for old, new in (("the sealed PDFs of the seven works and of the overview,", "the sealed PDFs of the seven works and of the overview volume,"),
                     ("The seven works and the overview are released", "The seven works and the overview volume are released")):
        assert decl.count(old) == 1, old[:60]
        decl = decl.replace(old, new)
    keys = refs.used([text, decl])
    (OUT / "01-overview.cited.md").write_text(refs.cite_text(text), encoding="utf-8", newline="\n")
    (OUT / "80-declarations.md").write_text(refs.cite_text(decl), encoding="utf-8", newline="\n")
    (OUT / "90-references.md").write_text("# References {.unnumbered}\n\n" + refs.reference_list(keys) + "\n",
                                          encoding="utf-8", newline="\n")
    (OUT / "ORDER.txt").write_text("# generated by tools/render_overview.py\n01-overview.cited.md\n80-declarations.md\n"
                                   "90-references.md\n", encoding="utf-8", newline="\n")
    body = re.sub(r"::: \{\.figure.*?\n:::\n", " ", text, flags=re.S)
    words = len(re.findall(r"[A-Za-z0-9’'-]+", re.sub(r"\[[^\]]*\]|\$[^$]*\$|:::.*|#.*|\|", " ", body)))
    print(f"overview: {len(keys)} references; {n} numbers checked against programme.yaml and the release record; "
          f"about {words} words of text")


if __name__ == "__main__":
    main()
